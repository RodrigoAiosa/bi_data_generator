"""
config.py — Configuração da página, slider de volume e registro de setores.

SETORES mapeia nome de exibição -> nome do módulo em generators/ (string),
em vez de importar as 213 funções gerar_<setor> de uma vez no import deste
arquivo. Cada gerador só é importado (via obter_gerador) quando o usuário
realmente seleciona aquele setor, o que evita instanciar ~200 objetos
Faker (um por módulo) e executar o import de módulos que nunca serão
usados na sessão — o maior custo de cold start do app.
"""

import importlib
from typing import Callable

import pandas as pd

_GERADOR_CACHE: dict[str, Callable[..., dict[str, pd.DataFrame]]] = {}


def obter_gerador(setor: str) -> Callable[..., dict[str, pd.DataFrame]]:
    """Importa (e cacheia) sob demanda a função gerar_<setor> do setor escolhido."""
    fn = _GERADOR_CACHE.get(setor)
    if fn is not None:
        return fn
    modname = SETORES[setor]
    modulo = importlib.import_module(f"generators.{modname}")
    fn = getattr(modulo, f"gerar_{modname}")
    _GERADOR_CACHE[setor] = fn
    return fn


